CREATE TABLE IF NOT EXISTS items (
 id TEXT PRIMARY KEY, kind TEXT NOT NULL, slug TEXT NOT NULL UNIQUE,
 draft TEXT NOT NULL, published TEXT, version INTEGER NOT NULL DEFAULT 1,
 updated TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS revisions (
 id TEXT PRIMARY KEY, item_id TEXT NOT NULL, action TEXT NOT NULL,
 snapshot TEXT NOT NULL, created TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS revisions_item ON revisions(item_id, created DESC);
CREATE TABLE IF NOT EXISTS sessions (
 token TEXT PRIMARY KEY, csrf TEXT NOT NULL, expires INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS login_limits (
 bucket TEXT PRIMARY KEY, count INTEGER NOT NULL, expires INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS media (
 id TEXT PRIMARY KEY, mime TEXT NOT NULL, data TEXT NOT NULL, created TEXT NOT NULL
);
